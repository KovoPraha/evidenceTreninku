<?php

declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

/** @return list<string> */
function uiAssetVersionPaths(): array
{
    return ['assets/vendor/bootstrap/bootstrap.min.css', 'assets/vendor/bootstrap/bootstrap.bundle.min.js',
        'assets/vendor/bootstrap-icons/font/bootstrap-icons.css', 'assets/app-ui.css', 'assets/app-ui.js'];
}

/** Build offline; web requests only load the committed, opcode-cacheable array. */
function uiAssetVersionManifest(string $root): string
{
    $root = realpath($root);
    if ($root === false || !is_dir($root . '/includes')) {
        throw new RuntimeException('An application root is required.');
    }
    $entries = [];
    foreach (uiAssetVersionPaths() as $path) {
        $file = realpath($root . '/' . $path);
        if ($file === false || !str_starts_with($file, $root . DIRECTORY_SEPARATOR) || !is_file($file) || is_link($root . '/' . $path)) {
            throw new RuntimeException('A regular owned UI asset is required: ' . $path);
        }
        $hash = hash_file('sha256', $file);
        if (!is_string($hash)) {
            throw new RuntimeException('Cannot hash UI asset: ' . $path);
        }
        $entries[] = '    ' . var_export($path, true) . ' => ' . var_export($hash, true) . ',';
    }
    return "<?php\n\ndeclare(strict_types=1);\n\n// Generated by tools/build-ui-asset-versions.php --write; do not edit by hand.\n"
        . "if (PHP_SAPI !== 'cli' && realpath((string) (\$_SERVER['SCRIPT_FILENAME'] ?? '')) === __FILE__) {\n"
        . "    http_response_code(404);\n    exit;\n}\n\nreturn [\n" . implode("\n", $entries) . "\n];\n";
}

/** @param list<string> $arguments */
function uiAssetVersionMain(array $arguments): int
{
    $mode = $arguments[1] ?? '--check';
    $root = dirname(__DIR__);
    if (isset($arguments[2]) && str_starts_with($arguments[2], '--root=')) {
        $root = substr($arguments[2], 7);
    }
    if (!in_array($mode, ['--check', '--write'], true) || count($arguments) > 3) {
        fwrite(STDERR, "Usage: php tools/build-ui-asset-versions.php [--check|--write] [--root=APPLICATION_ROOT]\n");
        return 2;
    }
    $expected = uiAssetVersionManifest($root);
    $target = $root . '/includes/ui_asset_versions.php';
    if ($mode === '--write') {
        if (file_put_contents($target, $expected, LOCK_EX) !== strlen($expected)) {
            throw new RuntimeException('Cannot write UI manifest.');
        }
    } elseif (!is_file($target) || str_replace("\r\n", "\n", (string) file_get_contents($target)) !== $expected) {
        fwrite(STDERR, "UI asset manifest is stale. Run php tools/build-ui-asset-versions.php --write after editing assets.\n");
        return 1;
    }
    echo 'UI asset manifest ' . ($mode === '--write' ? 'written' : 'verified') . ': 5 canonical payloads.' . PHP_EOL;
    return 0;
}

if (realpath((string) ($_SERVER['SCRIPT_FILENAME'] ?? '')) === __FILE__) {
    exit(uiAssetVersionMain($argv));
}
