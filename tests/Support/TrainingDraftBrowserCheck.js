async (page) => {
 const results=[];
 const check=(value,name)=>{if(!value)throw Error(name);results.push(name);};
 await page.evaluate(() => localStorage.clear());
 await page.reload();
 await page.getByRole('textbox',{name:'Náplň',exact:true}).fill('Dlouhý text tréninku LOCALHOST');
 await page.getByRole('textbox',{name:'Poznámka',exact:true}).fill('Poznámka nezmizí');
 await page.getByRole('combobox',{name:'Typ měření',exact:true}).selectOption('kolo');
 await page.getByRole('textbox',{name:'Sportovec pro měření',exact:true}).fill('Test LOCALHOST');
 await page.locator('.js-sp-id').evaluate(el=>{el.value='123';el.dispatchEvent(new Event('input',{bubbles:true}));});
 await page.getByRole('spinbutton',{name:'Vzdálenost',exact:true}).fill('200');
 await page.getByRole('combobox',{name:'Jednotka vzdálenosti',exact:true}).selectOption('m');
 await page.getByRole('textbox',{name:'Čas měření',exact:true}).fill('13,456');
 await page.getByRole('button',{name:'Uložit',exact:true}).click();
 check(await page.evaluate(()=>window.submissions===0),'invalid time blocked');
 check(await page.locator('.js-cas').evaluate(el=>!el.validity.valid && el.validationMessage.includes('00:13.456')),'time hint');
 await page.reload();
 check(await page.locator('#napln').inputValue()==='Dlouhý text tréninku LOCALHOST','reload text');
 check(await page.locator('.js-cas').inputValue()==='13,456','reload invalid measurement');
 check(await page.locator('.js-sp-id').inputValue()==='123','athlete binding retained');
 check(await page.locator('.js-vzdalenost').inputValue()==='200','distance retained');
 const reopened = await page.context().newPage();
 await reopened.goto(page.url());
 check(await reopened.locator('#napln').inputValue()==='Dlouhý text tréninku LOCALHOST','new tab restores text');
 await reopened.close();
 const again = await page.context().newPage();
 await again.goto(page.url());
 check(await again.locator('.js-cas').inputValue()==='13,456','closed tab reopened measurement');
 await again.close();
 await page.getByRole('textbox',{name:'Čas měření',exact:true}).fill('00:13x456');
 check(await page.locator('.js-cas').evaluate(el=>!el.validity.valid),'wildcard separator rejected');
 await page.getByRole('textbox',{name:'Čas měření',exact:true}).fill('00:00');
 check(await page.locator('.js-cas').evaluate(el=>!el.validity.valid),'zero rejected');
 await page.goto('http://127.0.0.1:18519/robots.txt');
 await page.goBack();
 check(await page.locator('#napln').inputValue()==='Dlouhý text tréninku LOCALHOST','back text');
 await page.getByRole('textbox',{name:'Čas měření',exact:true}).fill('00:13.456');
 await page.getByRole('button',{name:'Uložit',exact:true}).click();
 check(await page.evaluate(()=>window.submissions===1),'valid time submitted');
 await page.reload();
 check(await page.getByRole('textbox',{name:'Text uloženého konceptu'}).inputValue()==='Dlouhý text tréninku LOCALHOST\n\nPoznámka nezmizí','uncertain submission keeps text');
 check(await page.getByRole('button',{name:'Obnovit koncept',exact:true}).count()===0,'uncertain submission no blind replay');
 const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('kis-training-draft:v1:10:testkey')));
 await page.locator('#napln').fill('Do not overwrite uncertain submission');
 check(await page.evaluate(() => JSON.parse(localStorage.getItem('kis-training-draft:v1:10:testkey')).fields.napln[0])==='Dlouhý text tréninku LOCALHOST','uncertain draft not overwritten');
 const original = await (await page.request.get(page.url())).text();
 const config = {actor:10,key:'testkey',context:'0:0',completed:[],retry:{...saved,pending:false}};
 const response = value => original.replace(/(<script id="training-draft-config" type="application\/json">)[^<]+/, '$1'+JSON.stringify(value));
 await page.route('**/training-form.html', route => route.fulfill({body:response(config),contentType:'text/html'}));
 await page.reload();
 check(await page.locator('#napln').inputValue()==='Dlouhý text tréninku LOCALHOST','server rejection restores snapshot');
 await page.unroute('**/training-form.html');
 await page.route('**/training-form.html', route => route.fulfill({body:response({...config,actor:11,retry:null}),contentType:'text/html'}));
 await page.reload();
 check(await page.locator('#napln').inputValue()==='' && await page.locator('#training-draft-recovery').innerText()==='','other actor isolated');
 await page.unroute('**/training-form.html');
 await page.route('**/training-form.html', route => route.fulfill({body:response({...config,key:'nextkey',retry:null,completed:['testkey']}),contentType:'text/html'}));
 await page.reload();
 check(await page.evaluate(()=>localStorage.getItem('kis-training-draft:v1:10:testkey')===null),'confirmed success removes draft');
 await page.unroute('**/training-form.html');
 await page.evaluate(result => { document.body.dataset.testResult = JSON.stringify(result); }, {pass:results.length,results});
 await page.screenshot({path:'output/playwright/training-draft.png',fullPage:true});
}
